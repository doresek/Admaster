#!/usr/bin/env node
// db-drift-check.mjs — detect prod-vs-repo schema drift.
//
// Why: supabase/migrations/ has historically drifted from what's actually
// applied to prod (duplicate 003_*/004_* numbers, cherry-picked files), which
// silently broke /series, /refine, recommendations, scores, the notif bell, etc.
//
// What it does: parses every supabase/migrations/*.sql for the objects the repo
// EXPECTS (tables, functions, triggers), then emits a single SQL block you paste
// into the Supabase SQL Editor. That query returns ONLY the objects missing in
// prod — empty result ("No rows returned") means repo and prod are in sync.
//
// Usage:  node scripts/db-drift-check.mjs
// (prints the SQL; also writes it to /tmp/db-drift.sql)

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const MIG_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase', 'migrations');

const files = readdirSync(MIG_DIR).filter((f) => f.endsWith('.sql')).sort();
const sql = files.map((f) => readFileSync(join(MIG_DIR, f), 'utf8')).join('\n');

const grab = (re) => {
  const out = new Set();
  let m;
  while ((m = re.exec(sql))) out.add(m[1].toLowerCase());
  return [...out].sort();
};

const tables   = grab(/create\s+table\s+(?:if\s+not\s+exists\s+)?(?:public\.)?"?([a-z_][a-z0-9_]*)"?/gi);
const functions = grab(/create\s+(?:or\s+replace\s+)?function\s+(?:public\.)?"?([a-z_][a-z0-9_]*)"?\s*\(/gi);
const triggers = grab(/create\s+trigger\s+"?([a-z_][a-z0-9_]*)"?/gi);

const values = [
  ...tables.map((n) => `  ('table','${n}')`),
  ...functions.map((n) => `  ('function','${n}')`),
  ...triggers.map((n) => `  ('trigger','${n}')`),
].join(',\n');

const out = `-- AUTO-GENERATED by scripts/db-drift-check.mjs — DO NOT hand-edit.
-- Paste into the Supabase SQL Editor. Returns ONLY objects the repo defines
-- but prod is missing. Empty result = repo and prod are in sync.
-- Parsed from ${files.length} migration files: ${tables.length} tables, ${functions.length} functions, ${triggers.length} triggers.
with expected(kind, name) as (values
${values}
)
select e.kind, e.name as missing_in_prod
from expected e
where (e.kind = 'table' and not exists (
         select 1 from information_schema.tables t
         where t.table_schema = 'public' and t.table_name = e.name))
   or (e.kind = 'function' and not exists (
         select 1 from pg_proc p
         join pg_namespace n on n.oid = p.pronamespace
         where n.nspname = 'public' and p.proname = e.name))
   or (e.kind = 'trigger' and not exists (
         select 1 from pg_trigger tg
         where not tg.tgisinternal and tg.tgname = e.name))
order by 1, 2;
`;

writeFileSync('/tmp/db-drift.sql', out);
console.log(out);
console.error(`\n[db-drift-check] wrote /tmp/db-drift.sql — paste it into the Supabase SQL Editor.`);
